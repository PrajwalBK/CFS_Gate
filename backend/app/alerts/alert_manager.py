log = logging.getLogger('gate.alerts.manager')

def parse_container_pass_status(api_result: Any, raw_response: Optional[Dict[str, Any]] = None) -> str:
    """
    Inspects actual CFS backend API response to determine Container Pass generation status.
    Returns:
        - "PASS_GENERATED": Container pass is verified generated by cloud backend
        - "PASS_NOT_GENERATED": Backend explicitly confirmed pass was NOT generated
        - "UNKNOWN": Pending, network error, timeout, server error, or unconfirmed
    Strict rule: Never assume PASS_NOT_GENERATED for timeouts, network drops, or missing fields.
    """
    resp_obj = None
    status_code = None
    raw_text = ""

    if isinstance(api_result, dict):
        resp_obj = api_result
    if isinstance(raw_response, dict):
        status_code = raw_response.get('status_code')
        raw_text = str(raw_response.get('text') or '')
        if not resp_obj and isinstance(raw_response.get('json'), dict):
            resp_obj = raw_response.get('json')

    # 1. Inspect HTTP Success Responses (200, 201)
    if resp_obj:
        # Check top-level boolean fields
        for bool_key in ('passGenerated', 'isPassGenerated', 'pass_generated', 'hasPass', 'containerPassGenerated', 'gatePassGenerated'):
            if bool_key in resp_obj:
                val = resp_obj[bool_key]
                if val is True:
                    return 'PASS_GENERATED'
                if val is False:
                    return 'PASS_NOT_GENERATED'

        # Check top-level string status fields
        for str_key in ('passStatus', 'pass_status', 'containerPassStatus', 'gatePassStatus', 'passState', 'status'):
            if str_key in resp_obj and isinstance(resp_obj[str_key], str):
                v_upper = resp_obj[str_key].strip().upper()
                if v_upper in ('GENERATED', 'PASS_GENERATED', 'APPROVED', 'VALID', 'ACTIVE', 'ALLOWED', 'SUCCESS'):
                    return 'PASS_GENERATED'
                if v_upper in ('NOT_GENERATED', 'PASS_NOT_GENERATED', 'NOT_FOUND', 'EXPIRED', 'REJECTED', 'BLOCKED', 'DENIED', 'NO_PASS'):
                    return 'PASS_NOT_GENERATED'

        # Check nested containers list (e.g. Containers: [{passGenerated: false, ...}])
        containers = resp_obj.get('containers') or resp_obj.get('Containers')
        if isinstance(containers, list) and containers:
            any_not_generated = False
            all_generated = True
            for c in containers:
                if isinstance(c, dict):
                    c_pass_gen = c.get('passGenerated') if 'passGenerated' in c else c.get('isPassGenerated')
                    if c_pass_gen is False:
                        any_not_generated = True
                    elif c_pass_gen is True:
                        pass
                    else:
                        c_status = str(c.get('passStatus') or c.get('status') or '').strip().upper()
                        if c_status in ('NOT_GENERATED', 'PASS_NOT_GENERATED', 'REJECTED', 'BLOCKED'):
                            any_not_generated = True
                        elif c_status not in ('GENERATED', 'PASS_GENERATED', 'APPROVED', 'VALID'):
                            all_generated = False
                else:
                    all_generated = False

            if any_not_generated:
                return 'PASS_NOT_GENERATED'
            if all_generated and containers:
                return 'PASS_GENERATED'

        # Check explicit containerPass object
        if 'containerPass' in resp_obj:
            cp = resp_obj['containerPass']
            if cp is None or cp is False:
                return 'PASS_NOT_GENERATED'
            if isinstance(cp, dict) and (cp.get('id') or cp.get('passNumber')):
                return 'PASS_GENERATED'

    # 2. Inspect Client Error Responses (HTTP 400, 409, 422) for explicit pass rejection messages
    if status_code in (400, 409, 422) or raw_text:
        text_lower = raw_text.lower()
        if any(phrase in text_lower for phrase in (
            'pass not generated',
            'container pass not generated',
            'gate pass not generated',
            'no pass found',
            'pass missing',
            'pass_not_generated',
            'invalid pass'
        )):
            return 'PASS_NOT_GENERATED'

    # 3. Default to UNKNOWN for timeouts, network drops, server errors, or ambiguous formats
    return 'UNKNOWN'


class OutGateAlertManager:
    """
    Coordinates Out-Gate Alert lifecycle:
    - Inspects Gate-Out API response
    - Controls USB relay for exactly 8 seconds
    - Enforces duplicate prevention per event ID
    - Manages persistent logs and diagnostics
    """

    def __init__(self, config: Optional[AlertConfig] = None, relay: Optional[USBRelayController] = None):
        self.config = config or get_alert_config()
        self.relay = relay or get_relay_controller()
        self._lock = threading.Lock()
        self._siren_timer: Optional[threading.Timer] = None
        self._active_alert_event_id: Optional[str] = None
        self._triggered_events: set[str] = set()

        self._last_alert_triggered: Optional[str] = None
        self._last_alert_result: Optional[str] = None

        # Persistent history file in backend/data/alert_history.json
        base_dir = Path(__file__).resolve().parents[2]
        self._history_file = base_dir / "data" / "alert_history.json"
        self._logs: List[Dict[str, Any]] = self._load_history()

    def _load_history(self) -> List[Dict[str, Any]]:
        if self._history_file.exists():
            try:
                data = json.loads(self._history_file.read_text(encoding='utf-8'))
                if isinstance(data, list):
                    return data[-100:]  # Keep latest 100
            except Exception as e:
                log.warning('failed_to_load_alert_history: %s', e)
        return []

    def _save_history(self):
        try:
            self._history_file.parent.mkdir(parents=True, exist_ok=True)
            tmp = self._history_file.with_suffix('.tmp')
            tmp.write_text(json.dumps(self._logs[-100:], indent=2), encoding='utf-8')
            tmp.replace(self._history_file)
        except Exception as e:
            log.warning('failed_to_save_alert_history: %s', e)

    def handle_gate_api_response(self, event_id: str, event_type: str, container_number: str,
                                 api_result: Any, raw_response: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
        """
        Main decision integration point called immediately after Gate API response is received.
        Non-blocking, thread-safe.
        """
        now_iso = datetime.now(timezone.utc).isoformat()
        alert_id = str(uuid4())
        norm_type = (event_type or 'GATE_OUT').upper()

        # Rule 1: Gate-In events must NEVER activate the Out-Gate siren
        if norm_type in ('GATE_IN', 'ENTRY', 'IN'):
            log.info('alert_skipped_gate_in: event_id=%s container=%s', event_id, container_number)
            return {
                'alert_id': alert_id,
                'event_id': event_id,
                'container_number': container_number,
                'gate_type': norm_type,
                'backend_pass_status': 'N/A',
                'alert_enabled': self.config.is_enabled(),
                'relay_status': 'NOT_REQUIRED',
                'siren_duration': '0 Seconds',
                'final_status': 'NO ALERT (GATE_IN)'
            }

        # Rule 2: Evaluate actual Container Pass Status from backend API response
        pass_status = parse_container_pass_status(api_result, raw_response)
        alert_enabled = self.config.is_enabled()
        hw_connected = self.relay.is_connected()

        log.info('out_gate_alert_evaluating', extra={
            'event_id': event_id,
            'container_number': container_number,
            'pass_status': pass_status,
            'alert_enabled': alert_enabled,
            'hw_connected': hw_connected
        })

        # Decision matrix:
        # | Backend API result | Alerts setting | Siren action |
        # | PASS GENERATED     | ON / OFF       | OFF          |
        # | PASS NOT GENERATED | ON             | ON for 8s    |
        # | PASS NOT GENERATED | OFF            | OFF          |
        # | API timeout/unknown| ON / OFF       | OFF          |

        if pass_status == 'PASS_GENERATED':
            result_record = {
                'alert_id': alert_id,
                'event_id': event_id,
                'container_number': container_number,
                'gate_type': 'GATE_OUT',
                'backend_pass_status': 'PASS GENERATED',
                'alert_enabled': alert_enabled,
                'relay_status': 'NOT_REQUIRED',
                'siren_duration': '0 Seconds',
                'start_time': now_iso,
                'end_time': now_iso,
                'hardware_status': 'Connected' if hw_connected else 'Disconnected',
                'final_status': 'NO ALERT',
                'error_details': None
            }
            self._record_log(result_record)
            self._last_alert_result = f"Container {container_number}: PASS GENERATED (Siren OFF)"
            return result_record

        elif pass_status == 'PASS_NOT_GENERATED':
            if not alert_enabled:
                result_record = {
                    'alert_id': alert_id,
                    'event_id': event_id,
                    'container_number': container_number,
                    'gate_type': 'GATE_OUT',
                    'backend_pass_status': 'PASS NOT GENERATED',
                    'alert_enabled': False,
                    'relay_status': 'SKIPPED',
                    'siren_duration': '0 Seconds',
                    'start_time': now_iso,
                    'end_time': now_iso,
                    'hardware_status': 'Connected' if hw_connected else 'Disconnected',
                    'final_status': 'ALERT DISABLED',
                    'error_details': None
                }
                self._record_log(result_record)
                self._last_alert_result = f"Container {container_number}: PASS NOT GENERATED (Alert Disabled)"
                return result_record

            # PASS NOT GENERATED + Alerts ON: Check duplicate
            with self._lock:
                if event_id in self._triggered_events:
                    log.info('alert_skipped_duplicate_event: %s', event_id)
                    return {
                        'alert_id': alert_id,
                        'event_id': event_id,
                        'container_number': container_number,
                        'gate_type': 'GATE_OUT',
                        'backend_pass_status': 'PASS NOT GENERATED',
                        'alert_enabled': True,
                        'relay_status': 'DUPLICATE_SKIPPED',
                        'siren_duration': '0 Seconds',
                        'final_status': 'DUPLICATE'
                    }
                self._triggered_events.add(event_id)

            # ACTIVATE SIREN FOR 8 SECONDS
            duration = float(getattr(self.config, 'siren_duration_seconds', 8.0) or 8.0)
            relay_success = self._activate_siren(event_id, duration)

            final_status = 'COMPLETED' if relay_success else ('HARDWARE_DISCONNECTED' if not hw_connected else 'RELAY_FAILED')
            relay_status_str = 'SUCCESS' if relay_success else ('DISCONNECTED' if not hw_connected else 'FAILED')

            result_record = {
                'alert_id': alert_id,
                'event_id': event_id,
                'container_number': container_number,
                'gate_type': 'GATE_OUT',
                'backend_pass_status': 'PASS NOT GENERATED',
                'alert_enabled': True,
                'relay_status': relay_status_str,
                'siren_duration': f'{int(duration)} Seconds',
                'start_time': now_iso,
                'end_time': None,
                'hardware_status': 'Connected' if hw_connected else 'Disconnected',
                'final_status': final_status,
                'error_details': None if relay_success else self.relay.get_status().get('last_error')
            }
            self._record_log(result_record)
            self._last_alert_triggered = now_iso
            self._last_alert_result = f"Container {container_number}: PASS NOT GENERATED -> Siren ON for {int(duration)}s ({final_status})"
            return result_record

        else:
            # UNKNOWN / TIMEOUT / NETWORK ERROR -> No siren activation
            result_record = {
                'alert_id': alert_id,
                'event_id': event_id,
                'container_number': container_number,
                'gate_type': 'GATE_OUT',
                'backend_pass_status': 'UNKNOWN / TIMEOUT',
                'alert_enabled': alert_enabled,
                'relay_status': 'NOT_REQUIRED',
                'siren_duration': '0 Seconds',
                'start_time': now_iso,
                'end_time': now_iso,
                'hardware_status': 'Connected' if hw_connected else 'Disconnected',
                'final_status': 'NO ALERT (STATUS UNKNOWN)',
                'error_details': 'Pass status could not be confirmed generated or not generated'
            }
            self._record_log(result_record)
            self._last_alert_result = f"Container {container_number}: Unknown Pass Status (Siren OFF)"
            return result_record

    def _activate_siren(self, event_id: str, duration: float) -> bool:
        """Non-blocking activation of relay for duration seconds."""
        with self._lock:
            # Cancel any existing countdown timer
            if self._siren_timer and self._siren_timer.is_alive():
                self._siren_timer.cancel()
                self._siren_timer = None

            # Command relay ON
            success = self.relay.turn_on()
            self._active_alert_event_id = event_id

            # Start 8-second deactivation timer
            def _turn_off_callback():
                try:
                    self.relay.turn_off()
                    log.info('siren_auto_deactivated_after_duration: %ss', duration)
                except Exception as e:
                    log.warning('siren_auto_off_failed: %s', e)
                with self._lock:
                    self._active_alert_event_id = None
                    self._siren_timer = None

            self._siren_timer = threading.Timer(duration, _turn_off_callback)
            self._siren_timer.daemon = True
            self._siren_timer.start()

            return success

    def stop_siren(self) -> bool:
        """Immediately commands relay OFF and cancels active timer."""
        with self._lock:
            if self._siren_timer and self._siren_timer.is_alive():
                self._siren_timer.cancel()
                self._siren_timer = None
            self._active_alert_event_id = None
            return self.relay.turn_off()

    def set_master_switch(self, enabled: bool) -> bool:
        """Sets master switch ON/OFF. If set to OFF, immediately silences active siren."""
        res = self.config.set_enabled(enabled)
        if not enabled:
            self.stop_siren()
        return res

    def trigger_test_siren(self, duration: float = 8.0) -> bool:
        """Manual test trigger for UI verification."""
        alert_id = str(uuid4())
        now_iso = datetime.now(timezone.utc).isoformat()
        success = self._activate_siren(f"TEST-{alert_id[:8]}", duration)

        record = {
            'alert_id': alert_id,
            'event_id': f"MANUAL_TEST_{alert_id[:8]}",
            'container_number': 'TEST_SIREN',
            'gate_type': 'GATE_OUT',
            'backend_pass_status': 'MANUAL_TEST',
            'alert_enabled': self.config.is_enabled(),
            'relay_status': 'SUCCESS' if success else 'FAILED',
            'siren_duration': f'{int(duration)} Seconds',
            'start_time': now_iso,
            'end_time': None,
            'hardware_status': 'Connected' if self.relay.is_connected() else 'Disconnected',
            'final_status': 'TEST COMPLETED' if success else 'TEST FAILED',
            'error_details': None if success else self.relay.get_status().get('last_error')
        }
        self._record_log(record)
        self._last_alert_triggered = now_iso
        self._last_alert_result = f"Manual Test: Siren ON for {int(duration)}s"
        return success

    def _record_log(self, record: Dict[str, Any]):
        with self._lock:
            self._logs.append(record)
            if len(self._logs) > 100:
                self._logs = self._logs[-100:]
            self._save_history()

    def get_status(self) -> Dict[str, Any]:
        """Diagnostic state for UI polling."""
        hw = self.relay.get_status()
        with self._lock:
            is_siren_active = bool(self._siren_timer and self._siren_timer.is_alive())
            return {
                'master_switch_enabled': self.config.is_enabled(),
                'usb_relay_connected': hw.get('connected', False),
                'siren_controlled_by_relay': True,
                'relay_state': 'ON' if is_siren_active or hw.get('relay_state') == 'ON' else 'OFF',
                'device_description': hw.get('device_description', 'USB Relay Disconnected'),
                'device_type': hw.get('device_type', 'NONE'),
                'port': hw.get('port'),
                'last_alert_triggered': self._last_alert_triggered,
                'last_alert_result': self._last_alert_result,
                'recent_logs': list(reversed(self._logs[-25:]))
            }

_global_manager: Optional[OutGateAlertManager] = None

def get_alert_manager() -> OutGateAlertManager:
    global _global_manager
    if _global_manager is None:
        _global_manager = OutGateAlertManager()
    return _global_manager
